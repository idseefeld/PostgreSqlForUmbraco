[TestFixture]
public class BulkInsertTests
{
    private string _schema = null!;
    private string _connectionString = null!;
    private NpgsqlConnection _observer = null!;

    [SetUp]
    public void SetUp()
    {
        var connectionString = Environment.GetEnvironmentVariable("POSTGRES_TEST_CONNECTION_STRING")
            ?? throw new InvalidOperationException("Set POSTGRES_TEST_CONNECTION_STRING to a disposable PostgreSQL database. See tests/README.md.");
        _schema = "bulk_test_" + Guid.NewGuid().ToString("N");
        _connectionString = new NpgsqlConnectionStringBuilder(connectionString) { SearchPath = _schema, Pooling = false }.ConnectionString;
        _observer = new NpgsqlConnection(_connectionString);
        _observer.Open();
        Execute($"CREATE SCHEMA {_schema}");
        Execute("""
            CREATE TABLE bulk_records (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text UNIQUE);
            CREATE TABLE bulk_commands (query text NOT NULL);
            CREATE FUNCTION record_bulk_command() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
                INSERT INTO bulk_commands VALUES (current_query());
                RETURN NEW;
            END;
            $$;
            CREATE TRIGGER bulk_command AFTER INSERT ON bulk_records FOR EACH ROW EXECUTE FUNCTION record_bulk_command();
            """);
    }

    [TearDown]
    public void TearDown()
    {
        if (_observer is not null)
        {
            try
            {
                if (_observer.State == ConnectionState.Open)
                {
                    Execute($"DROP SCHEMA IF EXISTS {_schema} CASCADE");
                }
            }
            finally { _observer.Dispose(); }
        }
    }

    [TestCase(ConnectionMode.Raw)]
    [TestCase(ConnectionMode.Retry)]
    [TestCase(ConnectionMode.ProfiledRetry)]
    public void Bulk_insert_uses_copy_and_commits_its_transaction(ConnectionMode mode)
    {
        using var database = CreateDatabase(mode);
        var count = database.BulkInsertRecords(new[] { new Record { Value = "first" }, new Record { Value = "second" } });

        Assert.That(count, Is.EqualTo(2));
        Assert.That(database.InTransaction, Is.False, "The provider must complete a transaction it starts.");
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.EqualTo(2), "Rows must be visible to a separate connection.");
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_commands WHERE query LIKE 'COPY %'"), Is.EqualTo(2), "Successful INSERT fallback must not disguise a broken COPY path.");
    }

    [TestCase(ConnectionMode.Raw)]
    [TestCase(ConnectionMode.Retry)]
    [TestCase(ConnectionMode.ProfiledRetry)]
    public void Bulk_insert_preserves_the_callers_transaction(ConnectionMode mode)
    {
        using var database = CreateDatabase(mode);
        database.BeginTransaction();
        Assert.That(database.BulkInsertRecords(new[] { new Record { Value = "rollback" } }), Is.EqualTo(1));
        Assert.That(database.InTransaction, Is.True);
        Assert.That(database.ExecuteScalar<int>("SELECT count(*)::integer FROM bulk_commands WHERE query LIKE 'COPY %'"), Is.EqualTo(1));
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.Zero);
        database.AbortTransaction();
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.Zero);
    }

    [TestCase(ConnectionMode.Raw)]
    [TestCase(ConnectionMode.Retry)]
    [TestCase(ConnectionMode.Opaque)]
    public void Failed_bulk_insert_rolls_back_its_transaction(ConnectionMode mode)
    {
        using var database = CreateDatabase(mode);
        Assert.Throws<PostgresException>(() => database.BulkInsertRecords(new[] { new Record { Value = "duplicate" }, new Record { Value = "duplicate" } }));
        Assert.That(database.InTransaction, Is.False);
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.Zero);
        Assert.That(database.ExecuteScalar<int>("SELECT 1"), Is.EqualTo(1), "The connection must remain usable after rollback.");
    }

    [TestCase(ConnectionMode.Retry)]
    [TestCase(ConnectionMode.Opaque)]
    public void Failed_bulk_insert_leaves_the_callers_transaction_for_the_caller_to_abort(ConnectionMode mode)
    {
        using var database = CreateDatabase(mode);
        database.BeginTransaction();
        Assert.Throws<PostgresException>(() => database.BulkInsertRecords(new[] { new Record { Value = "duplicate" }, new Record { Value = "duplicate" } }));
        Assert.That(database.InTransaction, Is.True);
        database.AbortTransaction();
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.Zero);
        Assert.That(database.ExecuteScalar<int>("SELECT 1"), Is.EqualTo(1));
    }

    [Test]
    public void Bulk_insert_applies_column_mappers_and_preserves_nulls()
    {
        Execute("CREATE TABLE bulk_mapped (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value bigint NULL)");
        using var database = CreateDatabase(ConnectionMode.Retry);
        database.Mappers.Add(new IntegerToLongMapper());
        Assert.That(database.BulkInsertRecords(new[] { new MappedRecord { Value = 42 }, new MappedRecord() }), Is.EqualTo(2));
        Assert.That(Scalar<long>("SELECT value FROM bulk_mapped WHERE value IS NOT NULL"), Is.EqualTo(42L));
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_mapped WHERE value IS NULL"), Is.EqualTo(1));
    }

    [Test]
    public void Bulk_insert_omits_result_and_generated_columns()
    {
        Execute("ALTER TABLE bulk_records ADD generated text GENERATED ALWAYS AS (upper(value)) STORED");
        using var database = CreateDatabase(ConnectionMode.Retry);
        Assert.That(database.BulkInsertRecords(new[] { new RecordWithReadOnlyColumns { Value = "mixed" } }), Is.EqualTo(1));
        Assert.That(Scalar<string>("SELECT generated FROM bulk_records"), Is.EqualTo("MIXED"));
    }

    [TestCase(DateTimeKind.Utc)]
    [TestCase(DateTimeKind.Local)]
    [TestCase(DateTimeKind.Unspecified)]
    public void Bulk_insert_preserves_the_same_dates_as_normal_insert(DateTimeKind kind)
    {
        Execute("CREATE TABLE bulk_dates (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value timestamptz)");
        using var database = CreateDatabase(ConnectionMode.Retry);
        var value = new DateTime(2025, 5, 6, 12, 34, 56, kind);
        database.Insert(new DateRecord { Value = value });
        Assert.That(database.BulkInsertRecords(new[] { new DateRecord { Value = value } }), Is.EqualTo(1));
        Assert.That(Scalar<int>("SELECT count(DISTINCT value)::integer FROM bulk_dates"), Is.EqualTo(1));
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_dates"), Is.EqualTo(2));
    }

    [Test]
    public void Fallback_completes_its_transaction()
    {
        using var database = CreateDatabase(ConnectionMode.Opaque);
        Assert.That(database.BulkInsertRecords(new[] { new Record { Value = "fallback" } }), Is.EqualTo(1));
        Assert.That(database.InTransaction, Is.False);
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.EqualTo(1));
    }

    [Test]
    public void Fallback_preserves_the_callers_transaction()
    {
        using var database = CreateDatabase(ConnectionMode.Opaque);
        database.BeginTransaction();
        Assert.That(database.BulkInsertRecords(new[] { new Record { Value = "rollback" } }), Is.EqualTo(1));
        Assert.That(database.InTransaction, Is.True);
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.Zero);
        database.AbortTransaction();
        Assert.That(Scalar<int>("SELECT count(*)::integer FROM bulk_records"), Is.Zero);
    }

    [Test]
    public void Empty_input_does_not_open_a_connection_or_start_a_transaction()
    {
        using var database = CreateDatabase(ConnectionMode.Retry);
        Assert.That(database.BulkInsertRecords(Array.Empty<Record>()), Is.Zero);
        Assert.That(database.InTransaction, Is.False);
        Assert.That(database.Connection, Is.Null);
    }

    private TestDatabase CreateDatabase(ConnectionMode mode)
    {
        var syntax = new PostgreSqlSyntaxProvider(Options.Create(new PostgreSqlOptions()), NullLogger<PostgreSqlSyntaxProvider>.Instance);
        var context = new SqlContext(syntax, new UmbracoPostgreSQLDatabaseType(null!), new PocoDataFactory(new MapperCollection()));
        return new TestDatabase(_connectionString, context, mode);
    }

    private void Execute(string sql)
    {
        using var command = new NpgsqlCommand(sql, _observer);
        command.ExecuteNonQuery();
    }

    private T Scalar<T>(string sql)
    {
        using var command = new NpgsqlCommand(sql, _observer);
        return (T)command.ExecuteScalar()!;
    }

    public enum ConnectionMode { Raw, Retry, ProfiledRetry, Opaque }

    // Exercise the production interceptor with a real UmbracoDatabase and Npgsql connection.
    private sealed class TestDatabase(string connectionString, ISqlContext context, ConnectionMode mode)
        : UmbracoDatabase(connectionString, context, NpgsqlFactory.Instance, NullLogger<UmbracoDatabase>.Instance,
            new PostgreSqlBatchSqlInsertProvider(), null!)
    {
        protected override DbConnection OnConnectionOpened(DbConnection connection)
        {
            connection = base.OnConnectionOpened(connection);
            if (mode == ConnectionMode.Raw) return connection;
            if (mode == ConnectionMode.Opaque) return new OpaqueConnection(connection);
            using var services = new ServiceCollection()
                .Configure<ConnectionStrings>(options =>
                {
                    options.ConnectionString = ConnectionString;
                    options.ProviderName = Constants.ProviderName;
                }).BuildServiceProvider();
            var interceptor = new PostgreSqlAddRetryPolicyInterceptor(services.GetRequiredService<IOptionsMonitor<ConnectionStrings>>(), services);
            if (mode == ConnectionMode.ProfiledRetry) connection = new ProfiledDbConnection(connection, null);
            return interceptor.OnConnectionOpened(this, connection);
        }
    }

    // An unknown wrapper exercises the existing INSERT fallback without a second database engine.
    private sealed class OpaqueConnection(DbConnection inner) : DbConnection
    {
        [AllowNull]
        public override string ConnectionString { get => inner.ConnectionString; set => inner.ConnectionString = value; }
        public override string Database => inner.Database;
        public override string DataSource => inner.DataSource;
        public override string ServerVersion => inner.ServerVersion;
        public override ConnectionState State => inner.State;
        public override void Open() => inner.Open();
        public override void Close() => inner.Close();
        public override void ChangeDatabase(string databaseName) => inner.ChangeDatabase(databaseName);
        protected override DbTransaction BeginDbTransaction(IsolationLevel isolationLevel) => inner.BeginTransaction(isolationLevel);
        protected override DbCommand CreateDbCommand() => new OpaqueCommand(inner.CreateCommand(), this, inner);
        protected override void Dispose(bool disposing)
        {
            if (disposing) inner.Dispose();
            base.Dispose(disposing);
        }
    }

    private sealed class OpaqueCommand(DbCommand inner, DbConnection owner, DbConnection connection) : DbCommand
    {
        [AllowNull]
        public override string CommandText { get => inner.CommandText; set => inner.CommandText = value; }
        public override int CommandTimeout { get => inner.CommandTimeout; set => inner.CommandTimeout = value; }
        public override CommandType CommandType { get => inner.CommandType; set => inner.CommandType = value; }
        public override bool DesignTimeVisible { get => inner.DesignTimeVisible; set => inner.DesignTimeVisible = value; }
        public override UpdateRowSource UpdatedRowSource { get => inner.UpdatedRowSource; set => inner.UpdatedRowSource = value; }
        protected override DbConnection? DbConnection { get => owner; set => inner.Connection = value is null ? null : connection; }
        protected override DbTransaction? DbTransaction { get => inner.Transaction; set => inner.Transaction = value; }
        protected override DbParameterCollection DbParameterCollection => inner.Parameters;
        protected override DbParameter CreateDbParameter() => inner.CreateParameter();
        protected override DbDataReader ExecuteDbDataReader(CommandBehavior behavior) => inner.ExecuteReader(behavior);
        public override int ExecuteNonQuery() => inner.ExecuteNonQuery();
        public override object? ExecuteScalar() => inner.ExecuteScalar();
        public override void Prepare() => inner.Prepare();
        public override void Cancel() => inner.Cancel();
        protected override void Dispose(bool disposing)
        {
            if (disposing) inner.Dispose();
            base.Dispose(disposing);
        }
    }

    [TableName("bulk_records")]
    [PrimaryKey("id", AutoIncrement = true)]
    [ExplicitColumns]
    public class RecordWithReadOnlyColumns : Record
    {
        [ResultColumn("query_only")]
        public string? QueryOnly { get; set; }
        [ComputedColumn("generated")]
        public string? Generated { get; set; }
    }

    [TableName("bulk_dates")]
    [PrimaryKey("id", AutoIncrement = true)]
    [ExplicitColumns]
    public class DateRecord
    {
        [Column("id")]
        public int Id { get; set; }
        [Column("value")]
        public DateTime? Value { get; set; }
    }

    [TableName("bulk_mapped")]
    [PrimaryKey("id", AutoIncrement = true)]
    [ExplicitColumns]
    public class MappedRecord
    {
        [Column("id")]
        public int Id { get; set; }
        [Column("value")]
        public int? Value { get; set; }
    }

    private sealed class IntegerToLongMapper : DefaultMapper
    {
        public override Func<object, object> GetToDbConverter(Type destType, System.Reflection.MemberInfo sourceMemberInfo)
            => sourceMemberInfo.DeclaringType == typeof(MappedRecord) && sourceMemberInfo.Name == nameof(MappedRecord.Value)
                ? value => value is null ? DBNull.Value : Convert.ToInt64(value)
                : base.GetToDbConverter(destType, sourceMemberInfo);
    }

    [TableName("bulk_records")]
    [PrimaryKey("id", AutoIncrement = true)]
    [ExplicitColumns]
    public class Record
    {
        [Column("id")]
        public int Id { get; set; }
        [Column("value")]
        public string? Value { get; set; }
    }
}
